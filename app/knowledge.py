def match(text):
    """หัวข้อที่เกี่ยวกับชื่อ/คีย์ชุดข้อมูล"""
    t = (text or '').lower()
    out = []
    for k, v in TOPICS.items():
        for m in v.get('match') or []:
            if re.search(r'(?<![a-z])' + re.escape(m) + r'(?![a-z])', t) if m.isascii() and len(m) <= 4 else m in t:
                out.append(k)
                break
    return out


def get(topics=None, query=None):
    ks = [k for k in (topics or []) if k in TOPICS]
    if query:
        ks += [k for k in match(query) if k not in ks]
    if not ks:
        return dict(topics={k: v['title'] for k, v in TOPICS.items()}, hint='ระบุ topics หรือ query (ชื่อชุดข้อมูล/คำค้น)')
    return {k: {f: v for f, v in TOPICS[k].items() if f != 'match'} for k in ks}


def index_text():
    return 'คลังความรู้ข้อมูล (get_data_knowledge): ' + ' · '.join(f'{k} = {v["title"]}' for k, v in TOPICS.items())
